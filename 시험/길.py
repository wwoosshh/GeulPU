def 비트시험(m, prompts, 긴):
    """prompts: 문장 셋(토큰), 긴: 512 토큰 이상의 열."""
    b = {}
    seqs = [p + m.생성(p, N) for p in prompts]
    for j, S in enumerate(seqs):
        p = len(prompts[j])
        base = 글로짓(m, [S], "하나씩", p)[0]
        for 방식 in ("한번에", "프롬프트+하나씩", "두조각"):
            x = 글로짓(m, [S], 방식, p)[0]
            b[f"문장{j + 1} {방식} (하나씩 대비)"] = {"다른 칸": 다른칸(x, base), "칸 수": int(x.size)}
        g = m.생성(prompts[j], N, 기록=True)
        rec = m.기록된로짓(N)
        b[f"문장{j + 1} 생성 메가커널 (하나씩 대비)"] = {"다른 칸": 다른칸(rec, base[p:p + N - 1]), "칸 수": int(rec.size),
                                                "토큰이 같은가": g == S[p:p + N]}
    L = min(len(S) for S in seqs)
    cut = [S[:L] for S in seqs]
    alone = [글로짓(m, [S], "하나씩")[0] for S in cut]
    for 방식 in ("한번에", "하나씩"):
        x = 글로짓(m, cut, 방식)
        b[f"세 문장 한 묶음 {방식} (혼자 하나씩 대비)"] = {"다른 칸": sum(다른칸(x[j], alone[j]) for j in range(3)), "칸 수": int(x.size)}
    긴열 = 긴[:512]
    한번 = 로짓들(m, [긴열])
    c4 = {"혼자 대 세 문장 한 묶음: 다른 칸": 다른칸(로짓들(m, [cut[0]]), 로짓들(m, cut)),
          "한 번에 대 64토큰씩: 다른 칸": 다른칸(한번, 로짓들(m, [긴열], "조각", 64)),
          "한 번에 대 하나씩: 다른 칸": 다른칸(한번, 로짓들(m, [긴열], "하나씩")),
          "한 번에를 다섯 번 더: 첫 번째와 다른 칸": [다른칸(한번, 로짓들(m, [긴열])) for _ in range(5)]}
    out = {"길": b, "묶음 · 조각 · 되풀이": c4, "오류 칸": m.오류칸()}
    out["통과"] = (all(v["다른 칸"] == 0 and v.get("토큰이 같은가", True) for v in b.values()) and
                 all((x == 0 if not isinstance(x, list) else all(y == 0 for y in x)) for x in c4.values()) and out["오류 칸"] == 0)
    return out


def 끝끝(m, ids):
    """프롬프트(타일 — _KV정수 · 프롬프트 어텐션) · 두조각 · 메가커널로 채운 캐시 바이트가 하나씩(KV정수로 · 정수조각어텐션)으로 채운 것과 같은가."""
    b = {}
    base = 글로짓(m, [ids], "하나씩")[0]
    c하나 = 캐시(m)
    for 방식 in ("한번에", "두조각"):
        x = 글로짓(m, [ids], 방식)[0]
        c = 캐시(m)
        b[f"{방식} 대 하나씩"] = {"로짓 다른 칸": 다른칸(x, base), "캐시 다른 바이트 (키·값·키지수·값지수)": [int((p != q).sum()) for p, q in zip(c, c하나)]}
    p = 48
    S = ids[:p] + m.생성(ids[:p], N)
    base2 = 글로짓(m, [S], "하나씩", p)[0]
    g = m.생성(ids[:p], N, 기록=True)
    rec = m.기록된로짓(N)
    c메가 = 캐시(m)
    글로짓(m, [S[:p + N - 1]], "하나씩")
    b["생성 메가커널 대 하나씩"] = {"로짓 다른 칸": 다른칸(rec, base2[p:p + N - 1]), "토큰이 같은가": g == S[p:p + N],
                             "캐시 다른 바이트 (키·값·키지수·값지수)": [int((p_ != q).sum()) for p_, q in zip(c메가, 캐시(m))]}
    b["통과"] = all(all(x == 0 for x in v["캐시 다른 바이트 (키·값·키지수·값지수)"]) and v["로짓 다른 칸"] == 0 and v.get("토큰이 같은가", True)
                  for v in b.values() if isinstance(v, dict))
    return b


def 대화대조(m, rng, 차례들):
    """대화 길(이어넣기 · 이어생성 — 같은 길이를 다른 위치에서 다시 써 그래프의 위치 마디 고치기까지)이 같은 토큰열을 한 번에 넣은 것과
    토큰 · 캐시 바이트(층 모두, 키 · 값 · 지수)까지 같은가. 차례들: [(덩이 길이, 생성 수)]."""
    NL = len(m.kc)

    def 캐시모두():
        return [x for l in range(NL) for x in 캐시(m, l)]
    캐시비우기(m)
    열 = []                        # 넣은 토큰열(위치 차례)
    생성 = []                      # (위치, 토큰) — 위치의 행에서 고른 다음 토큰
    끝 = int(rng.integers(0, 50257))
    위치 = 0
    for 덩이길이, n in 차례들:
        덩이 = [끝] + [int(x) for x in rng.integers(0, 50257, 덩이길이 - 1)]
        첫 = m.이어넣기(덩이, 위치)
        열 += 덩이
        위치 += len(덩이)
        생성.append((위치 - 1, 첫))
        toks = m.이어생성(첫, 위치, n - 1) if n > 1 else [첫]
        for i, t in enumerate(toks[1:]):
            열.append(toks[i])
            생성.append((위치 + i, t))
        위치 += n - 1
        끝 = toks[-1]
    c대화 = 캐시모두()
    캐시비우기(m)
    로짓 = 글로짓(m, [열], "한번에")[0]
    c한번 = 캐시모두()
    고른 = {p: int(np.argmax(로짓[p])) for p, _ in 생성}
    다른토큰 = sum(1 for p, t in 생성 if 고른[p] != t)
    다른바이트 = int(sum(int((a != b).sum()) for a, b in zip(c대화, c한번)))
    return {"차례 (덩이, 생성)": 차례들, "토큰열 길이": len(열), "생성 토큰": len(생성), "다른 토큰": 다른토큰,
            "캐시 다른 바이트 (층 모두)": 다른바이트, "통과": 다른토큰 == 0 and 다른바이트 == 0}


def 메가대조(m, rng, 맥락들, 걸음=24):
    """생성 메가커널(머리마다 접는 블록) 대 따로 도는 커널(정수조각어텐션 + 정수조각접기)의 생성 — 토큰이 같은가(긴 엔진)."""
    out = {}
    for C0 in 맥락들:
        ids = [int(x) for x in rng.integers(0, 50257, C0)]
        첫 = None
        for a in range(0, C0, 1024):
            첫 = m.이어넣기(ids[a:a + 1024], a)
        가 = m.이어생성(첫, C0, 걸음 - 1)
        toks = [첫]
        for s in range(걸음 - 1):
            m.토큰넣기([toks[-1]])
            m.계산(1, 1, C0 + s, "끝")
            m.dr.맞추기()
            toks.append(int(m.dr.내리기(m.생성칸, np.zeros(1, np.int64))[0]))
        out[f"맥락 {C0}"] = {"같은가": toks == 가}
    out["통과"] = all(v["같은가"] for v in out.values())
    return out


def 나눠넣기대조(wq, rng, n=8192):
    """덩이를 여러 길이로 나눠 넣은 것(이어넣기 — 생성 판(행 넷까지 — 덩이 1 ~ 4), 묶음 판(질의 16 · 64 — 같은 덩이 48 을 위치 4096 너머까지
    되풀이해 그래프의 위치 마디가 판 · 격자를 바꾸게), 그리고 1024 까지의 덩이)과 한 번에 넣은 것(두 층 차례 판)이 위치 n 의 마지막 행 로짓 ·
    캐시 바이트(층 모두, 위치 0 … n−1)까지 같은가 — 긴 엔진(최대길이 102400)."""
    m = G.글GPT2(wq, KV형식="정수", 자리수=2, 최대행=n, 최대문장=1, 최대길이=102400, 로짓행=16)
    m.판미리고르기()
    ids = [int(x) for x in rng.integers(0, 50257, n)]
    덩이들 = [1000, 1, 2, 3, 4, 5, 16, 17, 32, 33] + [48] * 70 + [64, 100, 128, 192, 256, 300, 512, 1024, 1024]
    덩이들.append(n - sum(덩이들))
    assert 덩이들[-1] > 0
    캐시비우기(m)
    m.토큰넣기(ids)
    m.계산(1, n, 0, "끝", 출력자리=m.생성칸)
    한번 = m.로짓(1).copy()
    c한번 = [캐시앞(m, l, n) for l in range(len(m.kc))]
    캐시비우기(m)
    a = 0
    for L_ in 덩이들:
        m.이어넣기(ids[a:a + L_], a)
        a += L_
    나눔 = m.로짓(1).copy()
    c나눔 = [캐시앞(m, l, n) for l in range(len(m.kc))]
    out = {"덩이 수": len(덩이들), "마지막 행 로짓 다른 칸": 다른칸(한번, 나눔),
           "캐시 다른 바이트 (층 모두)": int(sum(int((x != y).sum()) for a_, b_ in zip(c한번, c나눔) for x, y in zip(a_, b_))),
           "오류 칸": m.오류칸()}
    out["통과"] = out["마지막 행 로짓 다른 칸"] == 0 and out["캐시 다른 바이트 (층 모두)"] == 0 and out["오류 칸"] == 0
    m.닫기()
    return out
